function scoreDim(text) {
  const t = (text || '').toLowerCase();
  const s = {};
  DIMS.forEach(d => s[d.key] = d.base);
  KW.forEach(k => { if (k.w.some(w => t.includes(w))) s[k.d] += 20; });
  Object.keys(s).forEach(k => { if (s[k] > 96) s[k] = 96; });
  return s;
}

/* 成长画像：评分 + 排序（与前端离线版一致，可叠加打卡 streak 加分） */
function buildPortrait(fields, streak = 0) {
  const s = {};
  DIMS.forEach(d => s[d.key] = d.base);
  (fields || []).forEach(txt => {
    const part = scoreDim(txt);
    DIMS.forEach(d => { s[d.key] = Math.min(96, s[d.key] + Math.round((part[d.key] - d.base) * 0.6)); });
  });
  if (streak >= 7) s.drive = Math.min(96, s.drive + 6);
  else if (streak >= 3) s.drive = Math.min(96, s.drive + 3);

  const vals = DIMS.map(d => Math.round(s[d.key]));
  const human = ['define', 'create', 'empath', 'drive'];
  const idx = Math.round(human.reduce((a, k) => a + s[k], 0) / human.length);
  const ranked = DIMS.map((d, i) => ({ key: d.key, name: d.name, value: vals[i] }))
    .sort((a, b) => b.value - a.value);
  const top = ranked.slice(0, 2);
  return {
    idx,
    dims: DIMS.map((d, i) => ({ key: d.key, name: d.name, value: vals[i] })),
    ranked,
    strong: top.map(t => t.name).join(' 与 '),
    topKey: top[0].key,
    topLabel: DIRS[top[0].key].label,
    secondLabel: top[1].name,
    suggest: DIRS[top[0].key],
    driveNote: streak >= 3 ? `已连续打卡 ${streak} 天，自驱与坚韧 +${streak >= 7 ? 6 : 3}` : '',
  };
}

/* 焦虑拆解：规则引擎匹配（按命中关键词的权重选最贴近的主题） */
function matchAnxiety(text) {
  const t = (text || '').toLowerCase();
  let best = ANX_DEFAULT, bestScore = 0;
  for (const a of ANX) {
    let score = 0;
    for (const w of a.k) { if (t.includes(w)) score += w.length >= 2 ? 2 : 1; }
    if (score > bestScore) { bestScore = score; best = a; }
  }
  const out = { reframe: best.reframe, can: best.can, cannot: best.cannot, next: best.next };
  if (bestScore > 0) {
    const q = String(text || '').trim().replace(/\s+/g, ' ');
    out.reframe = '你写下的是「' + (q.length > 26 ? q.slice(0, 26) + '…' : q) + '」。' + best.reframe;
  }
  return out;
}

/* 打卡连续天数（纯函数，传日期数组） */
function calcStreak(dates) {
  const set = new Set(dates);
  const d = new Date();
  let streak = 0;
  while (set.has(d.getFullYear() + '-' + (d.getMonth() + 1) + '-' + d.getDate())) {
    streak++;
    d.setDate(d.getDate() - 1);
  }
  return streak;
}

/* GAD-7 判读 */
function gad7Interpret(score) {
  let level, advice;
  if (score <= 4) {
    level = '正常';
    advice = '你的焦虑水平在正常范围内，继续保持规律作息与运动。';
  } else if (score <= 9) {
    level = '轻度焦虑';
    advice = '有轻度焦虑，可以试试青芽的「焦虑拆解」和「行动打卡」，规律作息、适度运动会有帮助。';
  } else if (score <= 14) {
    level = '中度焦虑';
    advice = '建议使用青芽的「焦虑拆解」与「7 天计划」，并考虑和学校心理中心聊一聊。';
  } else {
    level = '重度焦虑';
    advice = '建议尽快联系学校心理中心或辅导员，或拨打心理援助热线 12356（24 小时 · 免费）。';
  }
  return { score, level, advice, suggestHelp: score >= 10 };
}

